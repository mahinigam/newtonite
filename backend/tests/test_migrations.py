"""Schema creation is reproducible and stays in step with the ORM models."""

from __future__ import annotations

from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from tests.support import ALEMBIC_TABLE, ALL_TABLES, alembic_config


def test_models_and_migrations_do_not_drift(test_database_url: str) -> None:
    """`alembic check` fails if the models describe a schema the migrations do not.

    This is the regression guard for the most likely migration mistake: changing
    a model and forgetting the revision.
    """
    # Raises alembic.util.AutogenerateDiffsDetected when there is drift.
    command.check(alembic_config(test_database_url))


async def test_every_expected_table_exists(db: AsyncSession) -> None:
    result = await db.execute(text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'"))
    tables = {row.tablename for row in result}

    assert set(ALL_TABLES) <= tables
    assert tables - set(ALL_TABLES) == {ALEMBIC_TABLE}


async def test_alembic_version_is_recorded(db: AsyncSession, test_database_url: str) -> None:
    """The recorded revision is the migration head.

    The expected value is read from the migration scripts rather than pinned here, so
    adding a revision does not mean editing this assertion. The question the test asks is
    "is the database at head?", which stays the right question as the schema evolves.
    """
    head = ScriptDirectory.from_config(alembic_config(test_database_url)).get_current_head()
    version = (await db.execute(text("SELECT version_num FROM alembic_version"))).scalar_one()

    assert head is not None, "no migration script claims to be the head"
    assert version == head
